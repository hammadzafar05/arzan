// Bundles drizzle/*.sql into worker/db/migrations.gen.ts so the Worker can apply them itself.
// Runs after `drizzle-kit generate` (npm run db:generate). A test fails if the file is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const files = readdirSync("drizzle")
  .filter((f) => f.endsWith(".sql"))
  .sort();
const entries = files.map(
  (name) => `  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(readFileSync(`drizzle/${name}`, "utf8"))} },`,
);
const out = `// Generated by scripts/gen-migrations.mjs from drizzle/*.sql. Do not edit; run \`npm run db:generate\`.
export const MIGRATION_FILES: { name: string; sql: string }[] = [
${entries.join("\n")}
];
`;
writeFileSync("worker/db/migrations.gen.ts", out);
console.log(`worker/db/migrations.gen.ts: ${files.length} migration(s)`);
